(* Generates a Sarek kernel module for one prime field; the emitters live
   in field_emit.ml (shared with gen_walk.ml, where the arithmetic and the
   overflow bound are described).

   Usage: gen_field.exe NAME [OPS]   (NAME: ed25519 | secp256k1 | p256 | bls12_381;
   OPS: comma-separated subset of mul,add,sub,inv,batch_inv; default all) *)

open Field_emit

let () =
  let f =
    match List.find_opt (fun f -> Array.length Sys.argv > 1 && f.name = Sys.argv.(1)) fields with
    | Some f -> f
    | None -> prerr_endline "usage: gen_field NAME" ; exit 2
  in
  line "(* GENERATED by gen/gen_field.ml for %s -- do not edit. *)" f.name ;
  line "[@@@warning \"-26-27\"]\n" ;
  let wanted op =
    Array.length Sys.argv < 3 || List.mem op (String.split_on_char ',' Sys.argv.(2))
  in
  if wanted "mul" then binary_kernel f "mul" emit_mul ;
  if wanted "add" then binary_kernel f "add" emit_add ;
  if wanted "sub" then binary_kernel f "sub" emit_sub ;
  if wanted "inv" then inv_kernel f "inv" ;
  if wanted "batch_inv" then batch_inv_kernel f "batch_inv" ;
  print_string (Buffer.contents buf)
